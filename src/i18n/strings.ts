export function t(lang: Lang, key: string, ...args: (string | number)[]): string {
  let str = STRINGS[lang][key] ?? STRINGS.ar[key] ?? key;
  args.forEach((arg, idx) => {
    const pos = idx + 1;
    str = str.replace(new RegExp(`%${pos}\\$[sd]`, 'g'), String(arg));
  });
  return str;
}
